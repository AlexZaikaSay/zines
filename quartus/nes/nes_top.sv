// NES on the QMTECH Cyclone 10 LP board: FPGA counterpart of emulator/tb_200_video.sv.
// The cartridge is loaded from a raw .nes image on the SD card. No joysticks yet
// (both pads read as "nothing pressed").
//
// Video output is selected at build time:
//   default            640x480@60 VGA on the Pmod VGA (RGB444), no audio
//   `define VIDEO_HDMI 640x480p60 HDMI on the board connector, with 48 kHz audio
// (set it with the VERILOG_MACRO assignment in nes.qsf).
//
// Clock domains (all from nes_pll):
//   sd_clk    50.4 MHz  SD card + cartridge loader
//   ppu_clk   5.36 MHz  PPU, RAMs, cartridge CPU/PPU ports, frame buffer write side
//   cpu_clk   ppu_clk/3 generated by a register, exactly as in the testbench
//   pix_clk   25.2 MHz  video timing, frame buffer read side, HDMI encoder
//   tmds_clk  126 MHz   HDMI serializer (HDMI build only)
//
// Startup: the console is held in reset until the PLL locks and the cartridge reports
// `loaded`, then for 64 more PPU clocks. LEDR = ROM loaded, LED2 = load error.
module nes_top (
    input  logic       CLOCK_50,
    input  logic       RESET_N,

    // SD card socket (SPI mode)
    output logic       SD_CLK,
    output logic       SD_CMD,
    input  logic       SD_DAT0,
    output logic       SD_CS_N,
    input  logic       SD_CD,

`ifdef VIDEO_HDMI
    // HDMI connector: TMDS lanes 2..0 (red, green, blue) and clock, each pair driven
    // as two complementary 3.3-V LVTTL pins
    output logic [2:0] TMDS,
    output logic [2:0] TMDS_N,
    output logic       TMDS_CLK,
    output logic       TMDS_CLK_N,
`else
    // Pmod VGA on J11 (red, blue) and J10 (green, sync)
    output logic [3:0] VGA_R,
    output logic [3:0] VGA_G,
    output logic [3:0] VGA_B,
    output logic       VGA_HS,
    output logic       VGA_VS,
`endif

    output logic       LEDR,
    output logic       LED2
);
    localparam integer SD_CLK_HZ  = 50_400_000;
    localparam integer PIX_CLK_HZ = 25_200_000;

    // ----------------------------------------------------------------
    // Clocks and resets
    // ----------------------------------------------------------------
    logic ppu_clk, pix_clk, sd_clk, tmds_clk, pll_locked;

    nes_pll u_pll (
        .inclk(CLOCK_50),
        .ppu_clk(ppu_clk),
        .pix_clk(pix_clk),
        .sd_clk(sd_clk),
        .tmds_clk(tmds_clk),
        .locked(pll_locked)
    );

    wire sys_rst_n = RESET_N && pll_locked;

    logic sd_rst_n, pix_rst_n;

    reset_sync u_sd_rst  (.clk(sd_clk),  .arst_n(sys_rst_n), .rst_n(sd_rst_n));
    reset_sync u_pix_rst (.clk(pix_clk), .arst_n(sys_rst_n), .rst_n(pix_rst_n));

    // Startup pause: release the console only once the ROM is in the cartridge RAMs.
    logic cart_loaded, cart_error;
    logic loaded_rst_n;

    reset_sync u_ppu_rst (.clk(ppu_clk), .arst_n(sys_rst_n && cart_loaded), .rst_n(loaded_rst_n));

    logic [5:0] rst_cnt;
    logic       nes_rst_n;

    always_ff @(posedge ppu_clk or negedge loaded_rst_n) begin
        if (!loaded_rst_n) begin
            rst_cnt   <= 6'd0;
            nes_rst_n <= 1'b0;
        end
        else begin
            if (rst_cnt != 6'h3F)
                rst_cnt <= rst_cnt + 6'd1;
            nes_rst_n <= (rst_cnt == 6'h3F);
        end
    end

    // CPU clock = PPU clock / 3, free running like the testbench divider.
    // The SDC file declares this register as a generated clock.
    logic [1:0] phase   = 2'd0;
    logic       cpu_clk = 1'b0;

    always_ff @(posedge ppu_clk) begin
        phase   <= (phase == 2'd2) ? 2'd0 : phase + 2'd1;
        cpu_clk <= (phase == 2'd2);
    end

    // ----------------------------------------------------------------
    // Console
    // ----------------------------------------------------------------
    logic [8:0]  scanline;
    logic [8:0]  cycle;
    logic [7:0]  pixel_palette;
    logic [15:0] cart_cpu_addr;
    logic [7:0]  cart_cpu_data_out;
    logic [7:0]  cart_cpu_data_in;
    logic        cart_cpu_rw;
    logic        cart_cpu_ce_n;
    logic [13:0] cart_ppu_addr;
    logic        cart_ppu_rd_n;
    logic        cart_ppu_wr_n;
    logic [7:0]  cart_ppu_data_out;
    logic [7:0]  cart_ppu_data_in;
    logic        cart_ciram_a10;
    logic        cart_ciram_ce_n;
    logic [3:0]  audio1, audio2, audio3, audio4;

    nes_sim u_nes (
        .cpu_clk(cpu_clk),
        .ppu_clk(ppu_clk),
        .rst_n(nes_rst_n),
        .scanline(scanline),
        .cycle(cycle),
        .pixel_palette(pixel_palette),
        .joy1_strob(),
        .joy1_oe_n(),
        .joy1_data(8'h00),
        .joy2_oe_n(),
        .joy2_data(8'h00),
        .cart_cpu_addr(cart_cpu_addr),
        .cart_cpu_data_out(cart_cpu_data_out),
        .cart_cpu_data_in(cart_cpu_data_in),
        .cart_cpu_rw(cart_cpu_rw),
        .cart_cpu_ce_n(cart_cpu_ce_n),
        .cart_ppu_addr(cart_ppu_addr),
        .cart_ppu_rd_n(cart_ppu_rd_n),
        .cart_ppu_wr_n(cart_ppu_wr_n),
        .cart_ppu_data_out(cart_ppu_data_out),
        .cart_ppu_data_in(cart_ppu_data_in),
        .cart_ciram_a10(cart_ciram_a10),
        .cart_ciram_ce_n(cart_ciram_ce_n),
        .audio1(audio1),
        .audio2(audio2),
        .audio3(audio3),
        .audio4(audio4),
        .undef()
    );

    cartridge #(
        .CLK_FREQ_HZ(SD_CLK_HZ)
    ) u_cartridge (
        .clk(sd_clk),
        .bus_clk(ppu_clk),
        .reset_n(sd_rst_n),
        .sd_clk(SD_CLK),
        .sd_cmd(SD_CMD),
        .sd_dat0(SD_DAT0),
        .sd_cs_n(SD_CS_N),
        .sd_cd(SD_CD),
        .cpu_addr(cart_cpu_addr),
        .cpu_data_in(cart_cpu_data_out),
        .cpu_data_out(cart_cpu_data_in),
        .cpu_rw(cart_cpu_rw),
        .cpu_ce_n(cart_cpu_ce_n),
        .ppu_addr(cart_ppu_addr),
        .ppu_rd_n(cart_ppu_rd_n),
        .ppu_wr_n(cart_ppu_wr_n),
        .ppu_data_in(cart_ppu_data_out),
        .ppu_data_out(cart_ppu_data_in),
        .ciram_a10(cart_ciram_a10),
        .ciram_ce_n(cart_ciram_ce_n),
        .loaded(cart_loaded),
        .error(cart_error),
        .error_code()
    );

    // ----------------------------------------------------------------
    // Video (and audio for HDMI)
    // ----------------------------------------------------------------
    logic       video_hsync, video_vsync;
    logic [3:0] video_r, video_g, video_b;
    logic [9:0] video_x, video_y;

    nes_vga u_video (
        .ppu_clk(ppu_clk),
        .scanline(scanline),
        .cycle(cycle),
        .pixel_palette(pixel_palette),
        .vga_clk(pix_clk),
        .vga_rst_n(pix_rst_n),
        .hsync(video_hsync),
        .vsync(video_vsync),
        .red(video_r),
        .green(video_g),
        .blue(video_b),
        .pixel_x(video_x),
        .pixel_y(video_y)
    );

`ifdef VIDEO_HDMI
    logic [15:0] audio_sample;
    logic        audio_valid;

    nes_audio_sampler #(
        .PIXEL_CLK_HZ(PIX_CLK_HZ)
    ) u_audio (
        .ppu_clk(ppu_clk),
        .audio1(audio1),
        .audio2(audio2),
        .audio3(audio3),
        .audio4(audio4),
        .pix_clk(pix_clk),
        .pix_rst_n(pix_rst_n),
        .sample(audio_sample),
        .sample_valid(audio_valid)
    );

    logic [9:0] tmds_ch0, tmds_ch1, tmds_ch2;

    // RGB444 -> RGB888 by repeating the nibble, so 4'hF maps to full scale
    hdmi_tx #(
        .PIXEL_CLK_HZ(PIX_CLK_HZ)
    ) u_hdmi (
        .clk(pix_clk),
        .rst_n(pix_rst_n),
        .cx(video_x),
        .cy(video_y),
        .red({video_r, video_r}),
        .green({video_g, video_g}),
        .blue({video_b, video_b}),
        .audio_sample(audio_sample),
        .audio_valid(audio_valid),
        .tmds_ch0(tmds_ch0),
        .tmds_ch1(tmds_ch1),
        .tmds_ch2(tmds_ch2)
    );

    hdmi_serializer u_serializer (
        .tmds_clk(tmds_clk),
        .ch0(tmds_ch0),
        .ch1(tmds_ch1),
        .ch2(tmds_ch2),
        .tmds(TMDS),
        .tmds_n(TMDS_N),
        .tmds_clock(TMDS_CLK),
        .tmds_clock_n(TMDS_CLK_N)
    );

    wire unused_video = &{1'b0, video_hsync, video_vsync};
`else
    assign VGA_HS = video_hsync;
    assign VGA_VS = video_vsync;
    assign VGA_R  = video_r;
    assign VGA_G  = video_g;
    assign VGA_B  = video_b;

    wire unused_video = &{1'b0, video_x, video_y, tmds_clk, audio1, audio2, audio3, audio4};
`endif

    assign LEDR = cart_loaded;
    assign LED2 = cart_error;

endmodule


// Asynchronous assert, synchronous release.
module reset_sync (
    input  logic clk,
    input  logic arst_n,
    output logic rst_n
);
    logic [1:0] sync;

    always_ff @(posedge clk or negedge arst_n) begin
        if (!arst_n)
            sync <= 2'b00;
        else
            sync <= {sync[0], 1'b1};
    end

    assign rst_n = sync[1];

endmodule
