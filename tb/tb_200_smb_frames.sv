/* verilator lint_off STMTDLY */
/* verilator lint_off PROCASSINIT */

// Whole-console regression: runs SMB.nes headless with a scripted controller and
// compares a hash of every frame's picture and audio against tb/data/tb_200_smb_frames.tv.
// The console is wired exactly like sim/top/video.sv (nes + cartridge + cartridge_loader).
//
// Any change that moves a pixel or an audio sample by one clock shows up as the first
// frame that differs. If a difference is intended, re-record the reference:
//     build/obj_tb_200_smb_frames/Vtb_200_smb_frames +update     (run in build/)
//     cp build/tb_200_smb_frames.tv tb/data/
module tb_200_smb_frames;
    localparam string  ROM_FILE    = "../assets/SMB.nes";
    localparam string  GOLDEN_FILE = "tests/tb_200_smb_frames.tv";
    localparam string  UPDATE_FILE = "tb_200_smb_frames.tv";
    localparam integer FRAMES      = 420;

    // Controller script, in frames: Start on the title screen, then (after the
    // WORLD 1-1 screen) run right and jump every JUMP_EVERY frames
    localparam integer START_FROM  = 40;
    localparam integer START_TO    = 45;
    localparam integer RIGHT_FROM  = 100;
    localparam integer JUMP_EVERY  = 40;
    localparam integer JUMP_FOR    = 15;
    localparam logic [7:0] BTN_A     = 8'h01;
    localparam logic [7:0] BTN_START = 8'h08;
    localparam logic [7:0] BTN_RIGHT = 8'h80;

    logic clk = 1'b0;
    always #5 clk = ~clk;

    logic [7:0] rst_cnt = 8'd0;
    always @(posedge clk)
        if (rst_cnt != 8'd50) rst_cnt <= rst_cnt + 8'd1;
    wire rst_n = (rst_cnt == 8'd50);

    logic       cart_loaded;
    wire        nes_rst_n = rst_n && cart_loaded;

    // cpu_clk = clk / 3, generated by a register as in sim/top/video.sv
    logic [1:0] phase   = 2'd0;
    logic       cpu_clk = 1'b0;
    always_ff @(posedge clk) begin
        phase   <= (phase == 2'd2) ? 2'd0 : phase + 2'd1;
        cpu_clk <= (phase == 2'd2);
    end

    logic [8:0]  scanline, cycle;
    logic [7:0]  pixel_palette;
    logic        joy1_strob, joy1_oe_n, joy2_oe_n;
    logic [7:0]  joy1_data, joy2_data;
    logic [15:0] cart_cpu_addr;
    logic [7:0]  cart_cpu_data_in;
    logic        cart_cpu_rw, cart_cpu_ce_n;
    logic [13:0] cart_ppu_addr;
    logic        cart_ppu_rd_n, cart_ppu_wr_n;
    logic [7:0]  cart_ppu_data_out, cart_ppu_data_in;
    logic        cart_ciram_a10, cart_ciram_ce_n;
    logic [3:0]  audio1, audio2, audio3, audio4;
    logic        cpu_undef;

    nes dut (
        .cpu_clk(cpu_clk),
        .ppu_clk(clk),
        .rst_n(nes_rst_n),
        .scanline(scanline),
        .cycle(cycle),
        .pixel_palette(pixel_palette),
        .joy1_strob(joy1_strob),
        .joy1_oe_n(joy1_oe_n),
        .joy1_data(joy1_data),
        .joy2_oe_n(joy2_oe_n),
        .joy2_data(joy2_data),
        .cart_cpu_addr(cart_cpu_addr),
        .cart_cpu_data_in(cart_cpu_data_in),
        .cart_cpu_rw(cart_cpu_rw),
        .cart_cpu_ce_n(cart_cpu_ce_n),
        .cart_ppu_addr(cart_ppu_addr),
        .cart_ppu_rd_n(cart_ppu_rd_n),
        .cart_ppu_wr_n(cart_ppu_wr_n),
        .cart_ppu_data_out(cart_ppu_data_out),
        .cart_ppu_data_in(cart_ppu_data_in),
        .cart_ciram_a10(cart_ciram_a10),
        .cart_ciram_ce_n(cart_ciram_ce_n),
        .audio1(audio1),
        .audio2(audio2),
        .audio3(audio3),
        .audio4(audio4),
        .undef(cpu_undef)
    );

    logic [2:0]  cart_fill_w;
    logic [14:0] cart_init_addr;
    logic [7:0]  cart_init_data;
    logic [7:0]  cart_error_code;

    cartridge_loader #(
        .ROM_FILE(ROM_FILE)
    ) u_cart_loader (
        .clk(clk),
        .rst_n(rst_n),
        .fill_w(cart_fill_w),
        .addr(cart_init_addr),
        .data(cart_init_data),
        .done(cart_loaded),
        .error_code(cart_error_code)
    );

    cartridge u_cartridge (
        .clk(clk),
        .cpu_addr(cart_cpu_addr),
        .cpu_data_out(cart_cpu_data_in),
        .cpu_rw(cart_cpu_rw),
        .cpu_ce_n(cart_cpu_ce_n),
        .ppu_addr(cart_ppu_addr),
        .ppu_rd_n(cart_ppu_rd_n),
        .ppu_wr_n(cart_ppu_wr_n),
        .ppu_data_in(cart_ppu_data_out),
        .ppu_data_out(cart_ppu_data_in),
        .ciram_a10(cart_ciram_a10),
        .ciram_ce_n(cart_ciram_ce_n),
        .fill_w(cart_fill_w),
        .init_data_in(cart_init_data),
        .init_addr(cart_init_addr)
    );

    logic [7:0] pad_buttons = 8'h00;

    joystick_sim u_joystick (
        .strob(joy1_strob),
        .oe_n(joy1_oe_n),
        .buttons(pad_buttons),
        .data(joy1_data)
    );

    joystick_sim u_joystick2 (
        .strob(joy1_strob),
        .oe_n(joy2_oe_n),
        .buttons(8'h00),
        .data(joy2_data)
    );

    // Same power-on memory contents as sim/top/video.sv
    initial begin
        for (int i = 0; i < 2048; i++) begin
            dut.u_cpu_ram.data[i] = 8'h00;
            dut.u_ciram.data[i] = 8'h00;
        end
        for (int i = 0; i < 32; i++)
            dut.u_ppu.u_palette_ram.data[i] = 8'h0F;
    end

    // FNV-1a over the visible pixels of a frame and over the audio of a frame
    localparam logic [31:0] FNV_OFFSET = 32'h811C9DC5;
    localparam logic [31:0] FNV_PRIME  = 32'h01000193;

    wire unused = &{1'b0, pixel_palette[7:6]};

    function automatic logic [31:0] fnv(input logic [31:0] hash, input logic [7:0] value);
        return (hash ^ {24'd0, value}) * FNV_PRIME;
    endfunction

    logic [31:0] video_hash = FNV_OFFSET;
    logic [31:0] audio_hash = FNV_OFFSET;
    logic [31:0] golden_video [0:FRAMES-1];
    logic [31:0] golden_audio [0:FRAMES-1];
    integer      frame = 0;
    integer      golden_fd;
    integer      update_fd;
    logic        update;

    initial begin
        update = $test$plusargs("update");
        if (update) begin
            update_fd = $fopen(UPDATE_FILE, "w");
            if (update_fd == 0)
                $fatal(1, "Unable to create %s", UPDATE_FILE);
        end
        else begin
            golden_fd = $fopen(GOLDEN_FILE, "r");
            if (golden_fd == 0)
                $fatal(1, "Unable to open %s (record it with +update)", GOLDEN_FILE);
            for (int i = 0; i < FRAMES; i++)
                if ($fscanf(golden_fd, "%h %h\n", golden_video[i], golden_audio[i]) != 2)
                    $fatal(1, "%s: missing frame %0d", GOLDEN_FILE, i);
            $fclose(golden_fd);
        end
    end

    always @(posedge clk) begin
        if (nes_rst_n) begin
            if (scanline < 240 && cycle >= 1 && cycle <= 256)
                video_hash <= fnv(video_hash, {2'b00, pixel_palette[5:0]});

            if (cpu_clk)
                audio_hash <= fnv(fnv(audio_hash, {audio1, audio2}), {audio3, audio4});

            // End of the visible picture: compare and start the next frame
            if (scanline == 240 && cycle == 0) begin
                if (update)
                    $fwrite(update_fd, "%08h %08h\n", video_hash, audio_hash);
                else if (video_hash !== golden_video[frame] || audio_hash !== golden_audio[frame])
                    $fatal(1, "frame %0d differs: video %08h (expected %08h), audio %08h (expected %08h)",
                           frame, video_hash, golden_video[frame], audio_hash, golden_audio[frame]);

                video_hash <= FNV_OFFSET;
                audio_hash <= FNV_OFFSET;
                frame      <= frame + 1;

                if (frame + 1 >= START_FROM && frame + 1 < START_TO)
                    pad_buttons <= BTN_START;
                else if (frame + 1 >= RIGHT_FROM)
                    pad_buttons <= BTN_RIGHT | (((frame + 1) % JUMP_EVERY < JUMP_FOR) ? BTN_A : 8'h00);
                else
                    pad_buttons <= 8'h00;

                if (frame + 1 == FRAMES) begin
                    if (update) begin
                        $fclose(update_fd);
                        $display("Recorded %0d frames to %s", FRAMES, UPDATE_FILE);
                    end
                    else
                        $display("SMB: %0d frames match %s", FRAMES, GOLDEN_FILE);
                    $finish;
                end
            end
        end
    end

    always @(posedge clk) begin
        if (cart_loaded && cart_error_code != 0)
            $fatal(1, "cartridge load failed, error %02h", cart_error_code);
        if (cpu_undef === 1'b1)
            $fatal(1, "undefined opcode at %04h", dut.cpu_addr);
    end
endmodule
