// NES on the QMTECH Cyclone 10 LP board: FPGA counterpart of sim/top/video.sv.
// The cartridge is loaded from a raw .nes image on the SD card. A real NES controller
// is wired to player 1 (JOY_*); player 2 reads as "nothing pressed".
//
// Video output is selected at build time:
//   default            640x480@60 VGA on the Pmod VGA (RGB444), no audio
//   `define VIDEO_HDMI 640x480p60 HDMI on the board connector, with 48 kHz audio
// (set it with the VERILOG_MACRO assignment in nes.qsf).
//
// Clock domains (all from nes_pll):
//   sd_clk    50.4 MHz  SD card + cartridge loader
//   ppu_clk   5.36 MHz  PPU, RAMs, cartridge CPU/PPU ports, frame buffer write side
//   cpu_clk   ppu_clk/3 generated by a register, exactly as in the testbench
//   pix_clk   25.2 MHz  video timing, frame buffer read side, HDMI encoder
//   tmds_clk  126 MHz   HDMI serializer (HDMI build only)
//
// Startup: the console is held in reset until the PLL locks and the cartridge reports
// `loaded`, then for 64 more PPU clocks. LEDR = ROM loaded, LED2 = load error.
module nes_top (
    input  logic       CLOCK_50,
    input  logic       RESET_N,

    // SD card socket (SPI mode)
    output logic       SD_CLK,
    output logic       SD_CMD,
    input  logic       SD_DAT0,
    output logic       SD_CS_N,
    input  logic       SD_CD,

    // NES controller (CD4021 shift register), player 1
    output logic       JOY_LATCH,
    output logic       JOY_CLK,
    input  logic       JOY_DATA,

`ifdef VIDEO_HDMI
    // HDMI connector: TMDS lanes 2..0 (red, green, blue) and clock, each pair driven
    // as two complementary 3.3-V LVTTL pins
    output logic [2:0] TMDS,
    output logic [2:0] TMDS_N,
    output logic       TMDS_CLK,
    output logic       TMDS_CLK_N,
`else
    // Pmod VGA on J11 (red, blue) and J10 (green, sync)
    output logic [3:0] VGA_R,
    output logic [3:0] VGA_G,
    output logic [3:0] VGA_B,
    output logic       VGA_HS,
    output logic       VGA_VS,
`endif

    // 3-digit 7-segment display (debug): controller byte as read by the CPU
    output logic [7:0] SMG_Data,
    output logic [2:0] Scan_Sig,

    output logic       LEDR,
    output logic       LED2
);
    localparam integer SD_CLK_HZ  = 50_400_000;
    localparam integer PIX_CLK_HZ = 25_200_000;

    // ----------------------------------------------------------------
    // Clocks and resets
    // ----------------------------------------------------------------
    logic ppu_clk, pix_clk, sd_clk, tmds_clk, pll_locked;

    nes_pll u_pll (
        .inclk(CLOCK_50),
        .ppu_clk(ppu_clk),
        .pix_clk(pix_clk),
        .sd_clk(sd_clk),
        .tmds_clk(tmds_clk),
        .locked(pll_locked)
    );

    wire sys_rst_n = RESET_N && pll_locked;

    logic sd_rst_n, pix_rst_n;

    reset_sync u_sd_rst  (.clk(sd_clk),  .arst_n(sys_rst_n), .rst_n(sd_rst_n));
    reset_sync u_pix_rst (.clk(pix_clk), .arst_n(sys_rst_n), .rst_n(pix_rst_n));

    // Startup pause: release the console only once the ROM is in the cartridge RAMs.
    logic cart_loaded, cart_error;
    logic loaded_rst_n;

    reset_sync u_ppu_rst (.clk(ppu_clk), .arst_n(sys_rst_n && cart_loaded), .rst_n(loaded_rst_n));

    logic [5:0] rst_cnt;
    logic       nes_rst_n;

    always_ff @(posedge ppu_clk or negedge loaded_rst_n) begin
        if (!loaded_rst_n) begin
            rst_cnt   <= 6'd0;
            nes_rst_n <= 1'b0;
        end
        else begin
            if (rst_cnt != 6'h3F)
                rst_cnt <= rst_cnt + 6'd1;
            nes_rst_n <= (rst_cnt == 6'h3F);
        end
    end

    // CPU clock = PPU clock / 3, free running like the testbench divider.
    // The SDC file declares this register as a generated clock.
    logic [1:0] phase   = 2'd0;
    logic       cpu_clk = 1'b0;

    always_ff @(posedge ppu_clk) begin
        phase   <= (phase == 2'd2) ? 2'd0 : phase + 2'd1;
        cpu_clk <= (phase == 2'd2);
    end

    // ----------------------------------------------------------------
    // Console
    // ----------------------------------------------------------------
    logic [8:0]  scanline;
    logic [8:0]  cycle;
    logic [7:0]  pixel_palette;
    logic [15:0] cart_cpu_addr;
    logic [7:0]  cart_cpu_data_out;
    logic [7:0]  cart_cpu_data_in;
    logic        cart_cpu_rw;
    logic        cart_cpu_ce_n;
    logic [13:0] cart_ppu_addr;
    logic        cart_ppu_rd_n;
    logic        cart_ppu_wr_n;
    logic [7:0]  cart_ppu_data_out;
    logic [7:0]  cart_ppu_data_in;
    logic        cart_ciram_a10;
    logic        cart_ciram_ce_n;
    logic [3:0]  audio1, audio2, audio3, audio4;

    // ----------------------------------------------------------------
    // Controller port 1. The pad is polled by the FPGA with slow pulses
    // (nes_pad_poller) instead of being clocked by the CPU's $4016 reads: the
    // CSH-8088-3 clone does not follow the console's ~0.5 us clock pulses (each
    // button also appeared in the previous bit). nes_pad_port answers the CPU like
    // a CD4021 holding the last polled buttons.
    // DO is active low (pressed = 0), like an original pad.
    // ----------------------------------------------------------------
    logic       joy1_strob;
    logic       joy1_oe_n;
    logic [7:0] joy1_data;
    logic [7:0] pad1_buttons;
    logic       pad1_data;
    logic [1:0] joy_data_sync = 2'b11;

    always_ff @(posedge ppu_clk)
        joy_data_sync <= {joy_data_sync[0], JOY_DATA};

    nes_pad_poller #(
        .CLK_HZ(5_361_702),
        .ACTIVE_LOW(1'b1)
    ) u_pad1_poller (
        .clk(ppu_clk),
        .rst_n(loaded_rst_n),
        .pad_latch(JOY_LATCH),
        .pad_clk(JOY_CLK),
        .pad_data(joy_data_sync[1]),
        .buttons(pad1_buttons)
    );

    nes_pad_port u_pad1_port (
        .clk(ppu_clk),
        .rst_n(loaded_rst_n),
        .strobe(joy1_strob),
        .oe_n(joy1_oe_n),
        .buttons(pad1_buttons),
        .data(pad1_data)
    );

    assign joy1_data = {7'd0, pad1_data};

    // CPU-side edges for the debug capture below
    logic joy_latch_q = 1'b0;
    logic joy_clk_q   = 1'b1;

    always_ff @(posedge ppu_clk) begin
        joy_latch_q <= joy1_strob;
        joy_clk_q   <= joy1_oe_n;
    end

    // ----------------------------------------------------------------
    // Debug: record the bits the CPU reads after each strobe (1 = pressed,
    // bit 0 = A ... bit 7 = Right) and show them on the 7-segment display:
    // left digit = number of reads after the strobe, right digits = hex byte.
    // A read ends when oe_n rises; joy1_data still holds the bit it returned.
    // ----------------------------------------------------------------
    logic [7:0] dbg_bits;
    logic [3:0] dbg_count;
    logic [7:0] dbg_byte  = 8'h00;
    logic [3:0] dbg_reads = 4'h0;

    wire strobe_fall = joy_latch_q && !joy1_strob;
    wire read_end    = !joy_clk_q && joy1_oe_n;

    always_ff @(posedge ppu_clk) begin
        if (strobe_fall) begin
            // a new poll starts: publish the previous one
            dbg_byte  <= dbg_bits;
            dbg_reads <= dbg_count;
            dbg_bits  <= 8'h00;
            dbg_count <= 4'd0;
        end
        else if (read_end && !joy1_strob && dbg_count != 4'hF) begin
            if (dbg_count < 4'd8)
                dbg_bits[dbg_count[2:0]] <= joy1_data[0];
            dbg_count <= dbg_count + 4'd1;
        end
    end

    seg7_hex3 #(
        .SCAN_DIV(5_000)                    // ~1 ms per digit at ppu_clk
    ) u_seg7 (
        .clk(ppu_clk),
        .digits({dbg_reads, dbg_byte}),
        .seg(SMG_Data),
        .scan(Scan_Sig)
    );

    nes u_nes (
        .cpu_clk(cpu_clk),
        .ppu_clk(ppu_clk),
        .rst_n(nes_rst_n),
        .scanline(scanline),
        .cycle(cycle),
        .pixel_palette(pixel_palette),
        .joy1_strob(joy1_strob),
        .joy1_oe_n(joy1_oe_n),
        .joy1_data(joy1_data),
        .joy2_oe_n(),
        .joy2_data(8'h00),
        .cart_cpu_addr(cart_cpu_addr),
        .cart_cpu_data_out(cart_cpu_data_out),
        .cart_cpu_data_in(cart_cpu_data_in),
        .cart_cpu_rw(cart_cpu_rw),
        .cart_cpu_ce_n(cart_cpu_ce_n),
        .cart_ppu_addr(cart_ppu_addr),
        .cart_ppu_rd_n(cart_ppu_rd_n),
        .cart_ppu_wr_n(cart_ppu_wr_n),
        .cart_ppu_data_out(cart_ppu_data_out),
        .cart_ppu_data_in(cart_ppu_data_in),
        .cart_ciram_a10(cart_ciram_a10),
        .cart_ciram_ce_n(cart_ciram_ce_n),
        .audio1(audio1),
        .audio2(audio2),
        .audio3(audio3),
        .audio4(audio4),
        .undef()
    );

    cartridge #(
        .CLK_FREQ_HZ(SD_CLK_HZ)
    ) u_cartridge (
        .clk(sd_clk),
        .bus_clk(ppu_clk),
        .reset_n(sd_rst_n),
        .sd_clk(SD_CLK),
        .sd_cmd(SD_CMD),
        .sd_dat0(SD_DAT0),
        .sd_cs_n(SD_CS_N),
        .sd_cd(SD_CD),
        .cpu_addr(cart_cpu_addr),
        .cpu_data_in(cart_cpu_data_out),
        .cpu_data_out(cart_cpu_data_in),
        .cpu_rw(cart_cpu_rw),
        .cpu_ce_n(cart_cpu_ce_n),
        .ppu_addr(cart_ppu_addr),
        .ppu_rd_n(cart_ppu_rd_n),
        .ppu_wr_n(cart_ppu_wr_n),
        .ppu_data_in(cart_ppu_data_out),
        .ppu_data_out(cart_ppu_data_in),
        .ciram_a10(cart_ciram_a10),
        .ciram_ce_n(cart_ciram_ce_n),
        .loaded(cart_loaded),
        .error(cart_error),
        .error_code()
    );

    // ----------------------------------------------------------------
    // Video (and audio for HDMI)
    // ----------------------------------------------------------------
    logic       video_hsync, video_vsync;
    logic [3:0] video_r, video_g, video_b;
    logic [9:0] video_x, video_y;

    nes_vga u_video (
        .ppu_clk(ppu_clk),
        .scanline(scanline),
        .cycle(cycle),
        .pixel_palette(pixel_palette),
        .vga_clk(pix_clk),
        .vga_rst_n(pix_rst_n),
        .hsync(video_hsync),
        .vsync(video_vsync),
        .red(video_r),
        .green(video_g),
        .blue(video_b),
        .pixel_x(video_x),
        .pixel_y(video_y)
    );

`ifdef VIDEO_HDMI
    logic [15:0] audio_sample;
    logic        audio_valid;

    nes_audio_sampler #(
        .PIXEL_CLK_HZ(PIX_CLK_HZ)
    ) u_audio (
        .ppu_clk(ppu_clk),
        .audio1(audio1),
        .audio2(audio2),
        .audio3(audio3),
        .audio4(audio4),
        .pix_clk(pix_clk),
        .pix_rst_n(pix_rst_n),
        .sample(audio_sample),
        .sample_valid(audio_valid)
    );

    logic [9:0] tmds_ch0, tmds_ch1, tmds_ch2;

    // RGB444 -> RGB888 by repeating the nibble, so 4'hF maps to full scale
    hdmi_tx #(
        .PIXEL_CLK_HZ(PIX_CLK_HZ)
    ) u_hdmi (
        .clk(pix_clk),
        .rst_n(pix_rst_n),
        .cx(video_x),
        .cy(video_y),
        .red({video_r, video_r}),
        .green({video_g, video_g}),
        .blue({video_b, video_b}),
        .audio_sample(audio_sample),
        .audio_valid(audio_valid),
        .tmds_ch0(tmds_ch0),
        .tmds_ch1(tmds_ch1),
        .tmds_ch2(tmds_ch2)
    );

    hdmi_serializer u_serializer (
        .tmds_clk(tmds_clk),
        .ch0(tmds_ch0),
        .ch1(tmds_ch1),
        .ch2(tmds_ch2),
        .tmds(TMDS),
        .tmds_n(TMDS_N),
        .tmds_clock(TMDS_CLK),
        .tmds_clock_n(TMDS_CLK_N)
    );

    wire unused_video = &{1'b0, video_hsync, video_vsync};
`else
    assign VGA_HS = video_hsync;
    assign VGA_VS = video_vsync;
    assign VGA_R  = video_r;
    assign VGA_G  = video_g;
    assign VGA_B  = video_b;

    wire unused_video = &{1'b0, video_x, video_y, tmds_clk, audio1, audio2, audio3, audio4};
`endif

    assign LEDR = cart_loaded;
    assign LED2 = cart_error;

endmodule


// 3-digit multiplexed hex display (QMTECH board: segments and digit selects as in
// cartridge_demo; digits[11:8] is the left digit).
module seg7_hex3 #(
    parameter integer SCAN_DIV = 50_000
) (
    input  logic        clk,
    input  logic [11:0] digits,
    output logic [7:0]  seg,
    output logic [2:0]  scan
);
    logic [31:0] scan_counter = 32'd0;
    logic [1:0]  scan_digit   = 2'd0;
    logic [3:0]  nibble;

    always_ff @(posedge clk) begin
        if (scan_counter == 32'(SCAN_DIV - 1)) begin
            scan_counter <= 32'd0;
            scan_digit   <= (scan_digit == 2'd2) ? 2'd0 : scan_digit + 2'd1;
        end
        else begin
            scan_counter <= scan_counter + 32'd1;
        end
    end

    always_comb begin
        case (scan_digit)
            2'd0:    begin scan = 3'b100; nibble = digits[11:8]; end
            2'd1:    begin scan = 3'b010; nibble = digits[7:4];  end
            default: begin scan = 3'b001; nibble = digits[3:0];  end
        endcase

        case (nibble)
            4'h0: seg = 8'b1100_0000;
            4'h1: seg = 8'b1111_1001;
            4'h2: seg = 8'b1010_0100;
            4'h3: seg = 8'b1011_0000;
            4'h4: seg = 8'b1001_1001;
            4'h5: seg = 8'b1001_0010;
            4'h6: seg = 8'b1000_0010;
            4'h7: seg = 8'b1111_1000;
            4'h8: seg = 8'b1000_0000;
            4'h9: seg = 8'b1001_0000;
            4'hA: seg = 8'b1000_1000;
            4'hB: seg = 8'b1000_0011;
            4'hC: seg = 8'b1100_0110;
            4'hD: seg = 8'b1010_0001;
            4'hE: seg = 8'b1000_0110;
            default: seg = 8'b1000_1110;
        endcase
    end

endmodule


// Asynchronous assert, synchronous release.
module reset_sync (
    input  logic clk,
    input  logic arst_n,
    output logic rst_n
);
    logic [1:0] sync;

    always_ff @(posedge clk or negedge arst_n) begin
        if (!arst_n)
            sync <= 2'b00;
        else
            sync <= {sync[0], 1'b1};
    end

    assign rst_n = sync[1];

endmodule
